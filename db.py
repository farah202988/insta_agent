def set_order_status(pk, new_status):
    if new_status not in STATUSES:
        return False
    with conn() as c:
        order = c.execute("SELECT * FROM orders WHERE id = %s FOR UPDATE", (int(pk),)).fetchone()
        if order is None or order["status"] == "annulee" or order["status"] == new_status:
            return False
        if new_status == "annulee":
            c.execute("UPDATE products SET stock = stock + %s WHERE ref = %s AND size = %s",
                      (order["quantity"], order["product_ref"], order["size"]))
        c.execute("UPDATE orders SET status = %s WHERE id = %s", (new_status, int(pk)))
        return True


def add_handoff(instagram_id, reason, last_message=""):
    with conn() as c:
        c.execute("INSERT INTO handoffs (instagram_id, reason, last_message, created_at) VALUES (%s, %s, %s, %s)",
                  (str(instagram_id), reason, last_message, now()))


def is_handoff(instagram_id):
    with conn() as c:
        row = c.execute("SELECT 1 AS found FROM handoffs WHERE instagram_id = %s AND resolved = 0 LIMIT 1",
                        (str(instagram_id),)).fetchone()
    return row is not None


def list_handoffs():
    with conn() as c:
        return c.execute("SELECT * FROM handoffs WHERE resolved = 0 ORDER BY id DESC").fetchall()


def resolve_handoff(instagram_id):
    with conn() as c:
        c.execute("UPDATE handoffs SET resolved = 1 WHERE instagram_id = %s", (str(instagram_id),))


def get_conversation_history(instagram_id, limit=20):
    """Retourne les derniers messages au format attendu par Gemini."""
    limit = max(1, min(int(limit), 20))
    with conn() as c:
        rows = c.execute("""SELECT role, content FROM (
            SELECT id, role, content FROM conversation_messages
            WHERE instagram_id = %s AND created_at >= NOW() - INTERVAL '30 days'
            ORDER BY id DESC LIMIT %s
        ) AS recent ORDER BY id ASC""", (str(instagram_id), limit)).fetchall()
    return [{"role": row["role"], "text": row["content"]} for row in rows]


def add_conversation_message(instagram_id, role, content):
    """Enregistre un message et garde seulement les 20 plus récents, sur 30 jours."""
    if role not in ("user", "model"):
        raise ValueError("Rôle de message invalide")
    with conn() as c:
        c.execute("DELETE FROM conversation_messages WHERE created_at < NOW() - INTERVAL '30 days'")
        c.execute("INSERT INTO conversation_messages (instagram_id, role, content) VALUES (%s, %s, %s)",
                  (str(instagram_id), role, str(content)[:10000]))
        c.execute("""DELETE FROM conversation_messages WHERE instagram_id = %s AND id NOT IN (
            SELECT id FROM conversation_messages WHERE instagram_id = %s
            ORDER BY id DESC LIMIT 20)""", (str(instagram_id), str(instagram_id)))


def counts():
    with conn() as c:
        new_orders = c.execute("SELECT COUNT(*) AS n FROM orders WHERE status = 'nouvelle'").fetchone()["n"]
        handoffs = c.execute("SELECT COUNT(*) AS n FROM handoffs WHERE resolved = 0").fetchone()["n"]
        out = c.execute("SELECT COUNT(*) AS n FROM products WHERE stock = 0").fetchone()["n"]
    return {"new_orders": new_orders, "handoffs": handoffs, "out_of_stock": out}
