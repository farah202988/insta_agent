"""Base de données de la boutique avec PostgreSQL (Supabase)."""
import os
from contextlib import contextmanager
from datetime import datetime

import psycopg
from psycopg.rows import dict_row

DATABASE_URL = os.environ.get("DATABASE_URL")
STATUSES = ["nouvelle", "confirmee", "livree", "annulee"]


@contextmanager
def conn():
    if not DATABASE_URL:
        raise RuntimeError("La variable DATABASE_URL n'est pas configurée.")
    connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, sslmode="require")
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def now():
    return datetime.now().strftime("%Y-%m-%d %H:%M")


