def search_products(query):
    words = [w for w in str(query).lower().split() if len(w) >= 3]
    found, scores = {}, {}
    for r in list_products():
        text = "{} {} {} {}".format(r["name"], r["category"], r["color"], r["ref"]).lower()
        score = sum(1 for w in words if w in text or w[:4] in text)
        if words and score == 0:
            continue
        scores[r["ref"]] = score
        p = found.setdefault(r["ref"], {"id": r["ref"], "name": r["name"], "color": r["color"],
                                       "price_tnd": r["price"], "sizes_available": []})
        if r["stock"] > 0:
            p["sizes_available"].append(r["size"])
    best = max(scores.values()) if scores else 0
    return [p for ref, p in found.items() if scores[ref] == best][:8]


def get_stock(ref, size):
    with conn() as c:
        row = c.execute("SELECT stock FROM products WHERE ref = %s AND size = %s", (str(ref), str(size))).fetchone()
    return row["stock"] if row else 0


def upsert_variant(ref, name, category, color, size, price, stock):
    with conn() as c:
        c.execute("""INSERT INTO products (ref, name, category, color, size, price, stock)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            ON CONFLICT (ref, size) DO UPDATE SET name = EXCLUDED.name,
            category = EXCLUDED.category, color = EXCLUDED.color,
            price = EXCLUDED.price, stock = EXCLUDED.stock""",
            (ref.strip(), name.strip(), category.strip().lower(), color.strip().lower(),
             str(size).strip(), int(price), int(stock)))


def update_variant(pk, stock, price):
    with conn() as c:
        c.execute("UPDATE products SET stock = %s, price = %s WHERE id = %s",
                  (max(0, int(stock)), max(0, int(price)), int(pk)))


def delete_variant(pk):
    with conn() as c:
        c.execute("DELETE FROM products WHERE id = %s", (int(pk),))


def place_order(ref, size, quantity, customer_name, phone, address, payment, instagram_id):
    try:
        quantity = int(quantity)
    except (ValueError, TypeError):
        return {"status": "error", "reason": "quantité invalide"}
    if quantity < 1 or quantity > 20:
        return {"status": "error", "reason": "quantité invalide"}

    with conn() as c:
        row = c.execute("SELECT * FROM products WHERE ref = %s AND size = %s FOR UPDATE",
                        (str(ref), str(size))).fetchone()
        if row is None:
            return {"status": "error", "reason": "produit ou pointure introuvable"}
        if row["stock"] < quantity:
            return {"status": "error", "reason": "stock insuffisant", "quantity_in_stock": row["stock"]}
        c.execute("UPDATE products SET stock = stock - %s WHERE id = %s", (quantity, row["id"]))
        total = row["price"] * quantity
        inserted = c.execute("""INSERT INTO orders (created_at, instagram_id, product_ref, product_name,
            color, size, quantity, total, customer_name, phone, address, payment, status)
            VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, 'nouvelle') RETURNING id""",
            (now(), instagram_id, row["ref"], row["name"], row["color"], row["size"], quantity,
             total, customer_name, phone, address, payment)).fetchone()
        order_id = inserted["id"]
        order_ref = "CMD-{:04d}".format(order_id)
        c.execute("UPDATE orders SET order_ref = %s WHERE id = %s", (order_ref, order_id))
        return {"status": "ok", "order_id": order_ref, "total_tnd": total}


